# Arithmetic operators
a = 20
b = 6

print(a + b) # Addition
print(a - b) # Subtraction
print(a * b) # Multiplication
print(a / b) # Division
print(a // b) # Floor division - takes floor values avoids decimal
print(a % b) # Remainder - returns the left-over value (modulo)
print(a ** b) # Power









