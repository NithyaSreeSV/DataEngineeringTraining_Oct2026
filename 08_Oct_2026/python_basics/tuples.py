cities = ("Hyderabad", "Mumbai", "Delhi", "Bangalore")

#Print tuple
print(cities)

#Print based on index
print(cities[0])
print(cities[2])
print(cities[-1])

#Iterate through loops
for city in cities:
    print(city)

# cities[0] = "Pune" - Tuples are immutable used in (lat,long), RGB values, etc

